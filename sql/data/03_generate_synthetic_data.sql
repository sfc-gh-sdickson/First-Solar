-- ============================================================================
-- First Solar Supply Chain Intelligence Agent
-- 03: Load Synthetic Data from Stage (CSV files)
-- ============================================================================
-- Prerequisites: Run generate_data.py to create CSV files, then PUT them to stage
-- PUT file:///path/to/csv/*.csv @FS_INTELLIGENCE.RAW.SC_DATA_STAGE AUTO_COMPRESS=FALSE;

USE DATABASE FS_INTELLIGENCE;
USE SCHEMA RAW;
USE WAREHOUSE FIRST_SOLAR_WH;

-- Create internal stage for CSV uploads
CREATE STAGE IF NOT EXISTS SC_DATA_STAGE
    FILE_FORMAT = (TYPE = CSV FIELD_OPTIONALLY_ENCLOSED_BY = '"' SKIP_HEADER = 1 NULL_IF = (''));

-- ── Load reference/dimension tables ─────────────────────────────────────────
COPY INTO PLANTS FROM @SC_DATA_STAGE/plants.csv
    FILE_FORMAT = (TYPE = CSV FIELD_OPTIONALLY_ENCLOSED_BY = '"' SKIP_HEADER = 1)
    ON_ERROR = ABORT_STATEMENT;

COPY INTO CUSTOMERS FROM @SC_DATA_STAGE/customers.csv
    FILE_FORMAT = (TYPE = CSV FIELD_OPTIONALLY_ENCLOSED_BY = '"' SKIP_HEADER = 1)
    ON_ERROR = ABORT_STATEMENT;

COPY INTO MATERIALS FROM @SC_DATA_STAGE/materials.csv
    FILE_FORMAT = (TYPE = CSV FIELD_OPTIONALLY_ENCLOSED_BY = '"' SKIP_HEADER = 1 NULL_IF = (''))
    ON_ERROR = ABORT_STATEMENT;

COPY INTO SUPPLIERS FROM @SC_DATA_STAGE/suppliers.csv
    FILE_FORMAT = (TYPE = CSV FIELD_OPTIONALLY_ENCLOSED_BY = '"' SKIP_HEADER = 1)
    ON_ERROR = ABORT_STATEMENT;

COPY INTO SUPPLIER_MATERIALS FROM @SC_DATA_STAGE/supplier_materials.csv
    FILE_FORMAT = (TYPE = CSV FIELD_OPTIONALLY_ENCLOSED_BY = '"' SKIP_HEADER = 1)
    ON_ERROR = ABORT_STATEMENT;

COPY INTO BILL_OF_MATERIALS FROM @SC_DATA_STAGE/bill_of_materials.csv
    FILE_FORMAT = (TYPE = CSV FIELD_OPTIONALLY_ENCLOSED_BY = '"' SKIP_HEADER = 1)
    ON_ERROR = ABORT_STATEMENT;

-- ── Load transactional tables ───────────────────────────────────────────────
COPY INTO MRP_DEMAND FROM @SC_DATA_STAGE/mrp_demand.csv
    FILE_FORMAT = (TYPE = CSV FIELD_OPTIONALLY_ENCLOSED_BY = '"' SKIP_HEADER = 1 NULL_IF = (''))
    ON_ERROR = ABORT_STATEMENT;

COPY INTO INVENTORY_SNAPSHOT FROM @SC_DATA_STAGE/inventory_snapshot.csv
    FILE_FORMAT = (TYPE = CSV FIELD_OPTIONALLY_ENCLOSED_BY = '"' SKIP_HEADER = 1)
    ON_ERROR = ABORT_STATEMENT;

COPY INTO PURCHASE_ORDERS FROM @SC_DATA_STAGE/purchase_orders.csv
    FILE_FORMAT = (TYPE = CSV FIELD_OPTIONALLY_ENCLOSED_BY = '"' SKIP_HEADER = 1 NULL_IF = (''))
    ON_ERROR = ABORT_STATEMENT;

COPY INTO PO_RECEIPTS FROM @SC_DATA_STAGE/po_receipts.csv
    FILE_FORMAT = (TYPE = CSV FIELD_OPTIONALLY_ENCLOSED_BY = '"' SKIP_HEADER = 1)
    ON_ERROR = ABORT_STATEMENT;

COPY INTO INVENTORY_TRANSFERS FROM @SC_DATA_STAGE/inventory_transfers.csv
    FILE_FORMAT = (TYPE = CSV FIELD_OPTIONALLY_ENCLOSED_BY = '"' SKIP_HEADER = 1 NULL_IF = (''))
    ON_ERROR = ABORT_STATEMENT;

COPY INTO SUPPLY_RECOMMENDATIONS FROM @SC_DATA_STAGE/supply_recommendations.csv
    FILE_FORMAT = (TYPE = CSV FIELD_OPTIONALLY_ENCLOSED_BY = '"' SKIP_HEADER = 1 NULL_IF = ('', 'False', 'True'))
    ON_ERROR = ABORT_STATEMENT;
UPDATE SUPPLY_RECOMMENDATIONS SET ACTION_TAKEN = FALSE WHERE ACTION_TAKEN IS NULL;

COPY INTO ANOMALY_ALERTS FROM @SC_DATA_STAGE/anomaly_alerts.csv
    FILE_FORMAT = (TYPE = CSV FIELD_OPTIONALLY_ENCLOSED_BY = '"' SKIP_HEADER = 1 NULL_IF = ('', 'False', 'True'))
    ON_ERROR = ABORT_STATEMENT;
UPDATE ANOMALY_ALERTS SET IS_RESOLVED = FALSE WHERE IS_RESOLVED IS NULL;

COPY INTO MANUFACTURING_SCHEDULE FROM @SC_DATA_STAGE/manufacturing_schedule.csv
    FILE_FORMAT = (TYPE = CSV FIELD_OPTIONALLY_ENCLOSED_BY = '"' SKIP_HEADER = 1 NULL_IF = (''))
    ON_ERROR = ABORT_STATEMENT;

-- ── Load forecast tables ────────────────────────────────────────────────────
COPY INTO PRODUCT_DEMAND_FORECAST FROM @SC_DATA_STAGE/product_demand_forecast.csv
    FILE_FORMAT = (TYPE = CSV FIELD_OPTIONALLY_ENCLOSED_BY = '"' SKIP_HEADER = 1 NULL_IF = (''))
    ON_ERROR = ABORT_STATEMENT;

COPY INTO DEMAND_FORECAST FROM @SC_DATA_STAGE/demand_forecast.csv
    FILE_FORMAT = (TYPE = CSV FIELD_OPTIONALLY_ENCLOSED_BY = '"' SKIP_HEADER = 1 NULL_IF = (''))
    ON_ERROR = ABORT_STATEMENT;

COPY INTO FORECAST_MODEL_META FROM @SC_DATA_STAGE/forecast_model_meta.csv
    FILE_FORMAT = (TYPE = CSV FIELD_OPTIONALLY_ENCLOSED_BY = '"' SKIP_HEADER = 1)
    ON_ERROR = ABORT_STATEMENT;

-- ── Verification ────────────────────────────────────────────────────────────
SELECT 'PLANTS' AS tbl, COUNT(*) AS row_count FROM PLANTS
UNION ALL SELECT 'CUSTOMERS', COUNT(*) FROM CUSTOMERS
UNION ALL SELECT 'MATERIALS', COUNT(*) FROM MATERIALS
UNION ALL SELECT 'SUPPLIERS', COUNT(*) FROM SUPPLIERS
UNION ALL SELECT 'SUPPLIER_MATERIALS', COUNT(*) FROM SUPPLIER_MATERIALS
UNION ALL SELECT 'BILL_OF_MATERIALS', COUNT(*) FROM BILL_OF_MATERIALS
UNION ALL SELECT 'MRP_DEMAND', COUNT(*) FROM MRP_DEMAND
UNION ALL SELECT 'INVENTORY_SNAPSHOT', COUNT(*) FROM INVENTORY_SNAPSHOT
UNION ALL SELECT 'PURCHASE_ORDERS', COUNT(*) FROM PURCHASE_ORDERS
UNION ALL SELECT 'PO_RECEIPTS', COUNT(*) FROM PO_RECEIPTS
UNION ALL SELECT 'INVENTORY_TRANSFERS', COUNT(*) FROM INVENTORY_TRANSFERS
UNION ALL SELECT 'SUPPLY_RECOMMENDATIONS', COUNT(*) FROM SUPPLY_RECOMMENDATIONS
UNION ALL SELECT 'ANOMALY_ALERTS', COUNT(*) FROM ANOMALY_ALERTS
UNION ALL SELECT 'MANUFACTURING_SCHEDULE', COUNT(*) FROM MANUFACTURING_SCHEDULE
UNION ALL SELECT 'PRODUCT_DEMAND_FORECAST', COUNT(*) FROM PRODUCT_DEMAND_FORECAST
UNION ALL SELECT 'DEMAND_FORECAST', COUNT(*) FROM DEMAND_FORECAST
ORDER BY tbl;
